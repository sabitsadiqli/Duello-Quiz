package com.sabit.duelloquiz.core.auth.firebase

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.GetCredentialProviderConfigurationException
import androidx.credentials.exceptions.GetCredentialUnsupportedException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.sabit.duelloquiz.core.auth.GoogleCredentialClient
import com.sabit.duelloquiz.core.auth.GoogleCredentialResult
import kotlin.coroutines.cancellation.CancellationException

/**
 * "Sign in with Google" button flow through Credential Manager. [serverClientId] is the OAuth
 * web client ID of the Firebase project (`default_web_client_id`, generated by the
 * google-services plugin); null means Google sign-in is not configured in this build.
 */
internal class CredentialManagerGoogleClient(
    private val serverClientId: String?,
) : GoogleCredentialClient {

    override suspend fun requestIdToken(activityContext: Context): GoogleCredentialResult {
        if (serverClientId.isNullOrBlank()) return GoogleCredentialResult.Unavailable
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(serverClientId).build())
            .build()
        return try {
            val credential = CredentialManager.create(activityContext)
                .getCredential(activityContext, request)
                .credential
            if (credential is CustomCredential && credential.type in GOOGLE_ID_TOKEN_TYPES) {
                GoogleCredentialResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleCredentialResult.Failed("unexpected_credential_type")
            }
        } catch (e: CancellationException) {
            throw e
        } catch (_: GetCredentialCancellationException) {
            GoogleCredentialResult.Cancelled
        } catch (_: NoCredentialException) {
            GoogleCredentialResult.NoAccount
        } catch (_: GetCredentialProviderConfigurationException) {
            GoogleCredentialResult.Unavailable
        } catch (_: GetCredentialUnsupportedException) {
            GoogleCredentialResult.Unavailable
        } catch (_: GoogleIdTokenParsingException) {
            GoogleCredentialResult.Failed("id_token_parsing")
        } catch (e: GetCredentialException) {
            GoogleCredentialResult.Failed(e.javaClass.simpleName)
        }
    }

    private companion object {
        val GOOGLE_ID_TOKEN_TYPES = setOf(
            GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL,
            GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_SIWG_CREDENTIAL,
        )
    }
}

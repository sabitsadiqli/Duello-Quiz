package com.sabit.duelloquiz.core.auth.di

import android.annotation.SuppressLint
import android.content.Context
import android.util.Log
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.sabit.duelloquiz.core.auth.AuthRepository
import com.sabit.duelloquiz.core.auth.GoogleCredentialClient
import com.sabit.duelloquiz.core.auth.fake.FakeGoogleCredentialClient
import com.sabit.duelloquiz.core.auth.fake.InMemoryAuthRepository
import com.sabit.duelloquiz.core.auth.firebase.CredentialManagerGoogleClient
import com.sabit.duelloquiz.core.auth.firebase.FirebaseAuthRepository
import dagger.Module
import dagger.Provides
import dagger.hilt.InstallIn
import dagger.hilt.android.qualifiers.ApplicationContext
import dagger.hilt.components.SingletonComponent
import javax.inject.Singleton

/**
 * Binds Firebase when the app has a configured FirebaseApp (google-services.json present, so
 * FirebaseInitProvider initialised it). Otherwise binds the in-memory fakes so the app still
 * builds and runs end to end. Firebase classes are never touched when it is not configured.
 */
@Module
@InstallIn(SingletonComponent::class)
internal object AuthModule {

    private const val TAG = "AuthModule"

    @Provides
    @Singleton
    fun provideAuthRepository(@ApplicationContext context: Context): AuthRepository =
        if (isFirebaseConfigured(context)) {
            FirebaseAuthRepository(FirebaseAuth.getInstance(), context)
        } else {
            Log.w(TAG, "Firebase is not configured; using InMemoryAuthRepository")
            InMemoryAuthRepository()
        }

    @Provides
    @Singleton
    fun provideGoogleCredentialClient(@ApplicationContext context: Context): GoogleCredentialClient =
        if (isFirebaseConfigured(context)) {
            CredentialManagerGoogleClient(serverClientId = webClientId(context))
        } else {
            FakeGoogleCredentialClient()
        }

    private fun isFirebaseConfigured(context: Context): Boolean = FirebaseApp.getApps(context).isNotEmpty()

    /**
     * `default_web_client_id` is generated by the google-services plugin from
     * google-services.json, so it cannot be referenced as R.string at compile time.
     */
    @SuppressLint("DiscouragedApi")
    private fun webClientId(context: Context): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id != 0) context.getString(id) else null
    }
}

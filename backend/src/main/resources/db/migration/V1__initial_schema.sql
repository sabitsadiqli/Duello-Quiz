-- Duello Quiz initial schema (docs/mvp-spec.md §6, docs/requirements/duel-protocol-gaps.md §4).
-- Later migrations only add; never edit an applied migration.
-- Requires PostgreSQL 13+ (gen_random_uuid() is built in).

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    firebase_uid  VARCHAR(128) NOT NULL,
    display_name  VARCHAR(40)  NOT NULL,
    avatar_url    TEXT,
    rating        INT          NOT NULL DEFAULT 1000,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_firebase_uid_key UNIQUE (firebase_uid),
    CONSTRAINT users_display_name_length CHECK (char_length(display_name) BETWEEN 2 AND 40)
);

-- ---------------------------------------------------------------------------
-- Content: categories, images, questions, options
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
    id          INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(32)  NOT NULL,
    name_i18n   JSONB        NOT NULL,
    icon_key    VARCHAR(32)  NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT categories_slug_key UNIQUE (slug),
    CONSTRAINT categories_slug_format CHECK (slug ~ '^[a-z]+$'),
    CONSTRAINT categories_icon_key_format CHECK (icon_key ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT categories_name_has_az CHECK (jsonb_typeof(name_i18n) = 'object' AND name_i18n ? 'az')
);

-- Image files live on disk (ImageStorage); only metadata is stored here (§5).
CREATE TABLE images (
    id              UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    storage_key     VARCHAR(255)  NOT NULL,
    thumb_key       VARCHAR(255)  NOT NULL,
    width           INT           NOT NULL,
    height          INT           NOT NULL,
    bytes           INT           NOT NULL,
    dominant_color  CHAR(7)       NOT NULL,
    licence         TEXT,
    author          TEXT,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT images_storage_key_key UNIQUE (storage_key),
    CONSTRAINT images_thumb_key_key UNIQUE (thumb_key),
    CONSTRAINT images_dimensions_positive CHECK (width > 0 AND height > 0 AND bytes > 0),
    CONSTRAINT images_dominant_color_format CHECK (dominant_color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE questions (
    id                UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    external_id       VARCHAR(64)  NOT NULL,
    category_id       INT          NOT NULL REFERENCES categories (id),
    difficulty        SMALLINT     NOT NULL,
    text_i18n         JSONB        NOT NULL,
    explanation_i18n  JSONB,
    image_id          UUID         REFERENCES images (id) ON DELETE SET NULL,
    image_alt_i18n    JSONB,
    status            VARCHAR(16)  NOT NULL,
    is_active         BOOLEAN      NOT NULL DEFAULT FALSE,
    -- SHA-256 of the canonical imported content; lets the importer skip unchanged files.
    content_hash      CHAR(64)     NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT questions_external_id_key UNIQUE (external_id),
    CONSTRAINT questions_difficulty_range CHECK (difficulty BETWEEN 1 AND 3),
    CONSTRAINT questions_status_values CHECK (status IN ('draft', 'reviewed', 'retired')),
    CONSTRAINT questions_only_reviewed_active CHECK (NOT is_active OR status = 'reviewed'),
    CONSTRAINT questions_text_has_az CHECK (jsonb_typeof(text_i18n) = 'object' AND text_i18n ? 'az')
);
-- Session/duel question selection: active questions per category.
CREATE INDEX questions_active_category_idx ON questions (category_id) WHERE is_active;
CREATE INDEX questions_image_idx ON questions (image_id) WHERE image_id IS NOT NULL;

CREATE TABLE options (
    id           UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    question_id  UUID         NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    text_i18n    JSONB        NOT NULL,
    is_correct   BOOLEAN      NOT NULL,
    position     SMALLINT     NOT NULL,
    CONSTRAINT options_question_position_key UNIQUE (question_id, position),
    CONSTRAINT options_position_range CHECK (position BETWEEN 1 AND 4),
    CONSTRAINT options_text_has_az CHECK (jsonb_typeof(text_i18n) = 'object' AND text_i18n ? 'az')
);
-- At most one correct option per question (the importer guarantees exactly one).
CREATE UNIQUE INDEX options_one_correct_idx ON options (question_id) WHERE is_correct;

-- ---------------------------------------------------------------------------
-- Single-player quiz
-- ---------------------------------------------------------------------------
CREATE TABLE quiz_sessions (
    id             UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id    INT          NOT NULL REFERENCES categories (id),
    status         VARCHAR(16)  NOT NULL DEFAULT 'active',
    correct_count  SMALLINT,
    started_at     TIMESTAMPTZ  NOT NULL,
    deadline_at    TIMESTAMPTZ  NOT NULL,
    finished_at    TIMESTAMPTZ,
    CONSTRAINT quiz_sessions_status_values CHECK (status IN ('active', 'finished', 'expired')),
    CONSTRAINT quiz_sessions_deadline_after_start CHECK (deadline_at > started_at),
    -- correct_count and finished_at are set exactly when the session is closed.
    CONSTRAINT quiz_sessions_closed_fields CHECK (
        (status = 'active' AND finished_at IS NULL AND correct_count IS NULL)
        OR (status <> 'active' AND finished_at IS NOT NULL AND correct_count IS NOT NULL)
    ),
    CONSTRAINT quiz_sessions_correct_count_range CHECK (correct_count IS NULL OR correct_count >= 0)
);
CREATE INDEX quiz_sessions_user_started_idx ON quiz_sessions (user_id, started_at DESC);
-- Expiry job: active sessions past their deadline.
CREATE INDEX quiz_sessions_active_deadline_idx ON quiz_sessions (deadline_at) WHERE status = 'active';

CREATE TABLE quiz_session_questions (
    session_id   UUID      NOT NULL REFERENCES quiz_sessions (id) ON DELETE CASCADE,
    question_id  UUID      NOT NULL REFERENCES questions (id),
    position     SMALLINT  NOT NULL,
    PRIMARY KEY (session_id, position),
    CONSTRAINT quiz_session_questions_distinct UNIQUE (session_id, question_id),
    CONSTRAINT quiz_session_questions_position_positive CHECK (position >= 1)
);
CREATE INDEX quiz_session_questions_question_idx ON quiz_session_questions (question_id);

CREATE TABLE quiz_answers (
    id           BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id   UUID         NOT NULL,
    question_id  UUID         NOT NULL REFERENCES questions (id),
    option_id    UUID         REFERENCES options (id),
    is_correct   BOOLEAN      NOT NULL,
    answered_at  TIMESTAMPTZ  NOT NULL,
    elapsed_ms   INT          NOT NULL,
    CONSTRAINT quiz_answers_session_question_key UNIQUE (session_id, question_id),
    -- An answer can only exist for a question of its own session.
    CONSTRAINT quiz_answers_session_question_fkey FOREIGN KEY (session_id, question_id)
        REFERENCES quiz_session_questions (session_id, question_id) ON DELETE CASCADE,
    CONSTRAINT quiz_answers_elapsed_non_negative CHECK (elapsed_ms >= 0),
    CONSTRAINT quiz_answers_timeout_is_wrong CHECK (option_id IS NOT NULL OR NOT is_correct)
);
CREATE INDEX quiz_answers_option_idx ON quiz_answers (option_id) WHERE option_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Duel (tables are created now so the duel engine only adds code)
-- Players are referenced with ON DELETE SET NULL: a deleted account is anonymized
-- ("Silinmiş oyunçu"). The outcome is stored per side ('a'/'b'), not per user, so it
-- survives the anonymization (docs/mvp-spec.md §3a, OQ-014).
-- ---------------------------------------------------------------------------
CREATE TABLE matches (
    id               UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    player_a         UUID         REFERENCES users (id) ON DELETE SET NULL,
    player_b         UUID         REFERENCES users (id) ON DELETE SET NULL,
    score_a          INT          NOT NULL DEFAULT 0,
    score_b          INT          NOT NULL DEFAULT 0,
    -- 'a', 'b' or NULL (draw, abandoned, cancelled, still active)
    winner_side      CHAR(1),
    status           VARCHAR(16)  NOT NULL DEFAULT 'active',
    end_reason       VARCHAR(16),
    forfeited_side   CHAR(1),
    rating_a_before  INT,
    rating_a_after   INT,
    rating_b_before  INT,
    rating_b_after   INT,
    started_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at      TIMESTAMPTZ,
    CONSTRAINT matches_status_values CHECK (status IN ('active', 'finished', 'abandoned', 'cancelled')),
    CONSTRAINT matches_end_reason_values CHECK (
        end_reason IS NULL OR end_reason IN ('normal', 'sudden_death', 'draw', 'forfeit', 'abandoned', 'cancelled')
    ),
    CONSTRAINT matches_winner_side_values CHECK (winner_side IS NULL OR winner_side IN ('a', 'b')),
    CONSTRAINT matches_forfeited_side_values CHECK (forfeited_side IS NULL OR forfeited_side IN ('a', 'b')),
    CONSTRAINT matches_closed_fields CHECK (
        (status = 'active' AND finished_at IS NULL AND end_reason IS NULL)
        OR (status <> 'active' AND finished_at IS NOT NULL AND end_reason IS NOT NULL)
    ),
    CONSTRAINT matches_forfeit_has_side CHECK ((end_reason = 'forfeit') = (forfeited_side IS NOT NULL))
);
CREATE INDEX matches_player_a_idx ON matches (player_a, finished_at DESC);
CREATE INDEX matches_player_b_idx ON matches (player_b, finished_at DESC);
CREATE INDEX matches_active_idx ON matches (started_at) WHERE status = 'active';

CREATE TABLE match_rounds (
    id                  BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    match_id            UUID         NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    round_no            SMALLINT     NOT NULL,
    question_id         UUID         NOT NULL REFERENCES questions (id),
    all_in              BOOLEAN      NOT NULL DEFAULT FALSE,
    sudden_death        BOOLEAN      NOT NULL DEFAULT FALSE,
    options_sent_at     TIMESTAMPTZ,
    answer_deadline_at  TIMESTAMPTZ,
    CONSTRAINT match_rounds_match_round_key UNIQUE (match_id, round_no),
    -- A question is never repeated inside one match.
    CONSTRAINT match_rounds_match_question_key UNIQUE (match_id, question_id),
    CONSTRAINT match_rounds_round_no_range CHECK (round_no BETWEEN 1 AND 10)
);
CREATE INDEX match_rounds_question_idx ON match_rounds (question_id);

CREATE TABLE match_answers (
    id             BIGINT    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    round_id       BIGINT    NOT NULL REFERENCES match_rounds (id) ON DELETE CASCADE,
    user_id        UUID      REFERENCES users (id) ON DELETE SET NULL,
    side           CHAR(1)   NOT NULL,
    bet            SMALLINT  NOT NULL,
    bet_defaulted  BOOLEAN   NOT NULL DEFAULT FALSE,
    option_id      UUID      REFERENCES options (id),
    is_correct     BOOLEAN   NOT NULL DEFAULT FALSE,
    -- server receive time minus the server time the options were sent; NULL = no answer
    answered_ms    INT,
    speed_bonus    INT       NOT NULL DEFAULT 0,
    points         INT       NOT NULL DEFAULT 0,
    missed         BOOLEAN   NOT NULL DEFAULT FALSE,
    CONSTRAINT match_answers_round_user_key UNIQUE (round_id, user_id),
    CONSTRAINT match_answers_round_side_key UNIQUE (round_id, side),
    CONSTRAINT match_answers_side_values CHECK (side IN ('a', 'b')),
    CONSTRAINT match_answers_bet_range CHECK (bet BETWEEN 1 AND 3),
    CONSTRAINT match_answers_speed_bonus_range CHECK (speed_bonus BETWEEN 0 AND 50),
    CONSTRAINT match_answers_answered_ms_non_negative CHECK (answered_ms IS NULL OR answered_ms >= 0)
);
CREATE INDEX match_answers_user_idx ON match_answers (user_id) WHERE user_id IS NOT NULL;
